const assert=require('node:assert/strict');
const {validateResources,resourceSection}=require('../../lib/company-resources');
const config=require('../../industry-map/research/site-resources.json');
const {load}=require('../../lib/atlas');
const providers=load().providers;
const optel=providers.find(p=>p.id==='optel');
assert.equal(optel.resources.length,1);
assert.equal(optel.resources[0].bytes,610129);
assert.equal(optel.resources[0].pages,3);
assert(resourceSection(optel).includes('download '));
assert(resourceSection(optel).includes('Provided by OPTEL'));
assert.equal(resourceSection(providers.find(p=>p.id==='altiushub')),'');
assert.throws(()=>validateResources(config,new Set()),/Unknown company/);
const malformed=JSON.parse(JSON.stringify(config));
malformed.optel[0].file='/assets/downloads/companies/optel/../private.pdf';
assert.throws(()=>validateResources(malformed,new Set(['optel','trackvision-ai'])),/Invalid resource asset/);
const missing=JSON.parse(JSON.stringify(config));
missing.optel[0].file='/assets/downloads/companies/optel/not-present.pdf';
assert.throws(()=>validateResources(missing,new Set(['optel','trackvision-ai'])),/Missing resource asset/);
const duplicate={optel:[config.optel[0],config.optel[0]]};
assert.throws(()=>validateResources(duplicate,new Set(['optel','trackvision-ai'])),/Only one featured resource/);
const trackvision=providers.find(p=>p.id==='trackvision-ai');
assert.equal(trackvision.resources[0].bytes,742681);
assert.equal(trackvision.resources[0].pages,4);
assert(resourceSection(trackvision).includes('Provided by TrackVision AI'));
console.log('PASS: resource metadata, empty profiles, file validation and one-resource limit.');
